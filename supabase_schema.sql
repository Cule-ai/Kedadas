-- Función SECURITY DEFINER corregida: Solo el email verificado o flag en DB otorgan superadmin
create or replace function public.is_superadmin()
returns boolean
language sql
security definer
set search_path = public, auth
stable
as $$
  select (
    -- 1. Verificación estricta en el JWT del correo de Cule
    lower(coalesce(auth.jwt()->>'email', '')) = 'maculecale@gmail.com'
    -- 2. O usuario con is_superadmin = true verificado en base de datos
    or exists (
      select 1
      from public.perfiles p
      where p.user_id = auth.uid()
        and p.is_superadmin = true
    )
  );
$$;

-- Trigger: Cuando un usuario se registra/conecta vía auth.users, vincular su perfil
create or replace function public.handle_new_user_roles()
returns trigger as $$
declare
  v_nombre text;
  v_email text;
  v_es_superadmin boolean := false;
begin
  v_email := lower(coalesce(new.email, ''));
  v_nombre := coalesce(new.raw_user_meta_data->>'nombre', split_part(v_email, '@', 1));

  if v_email = 'maculecale@gmail.com' then
    v_es_superadmin := true;
  end if;

  update public.perfiles
  set user_id = new.id,
      email = new.email,
      is_superadmin = case when v_es_superadmin then true else is_superadmin end,
      rol = case when v_es_superadmin then 'superadmin' else rol end
  where (email is not null and lower(email) = v_email) or user_id = new.id;

  if not found then
    insert into public.perfiles (user_id, email, nombre, rol, is_superadmin)
    values (
      new.id,
      new.email,
      v_nombre,
      case when v_es_superadmin then 'superadmin' else 'usuario' end,
      v_es_superadmin
    );
  end if;

  return new;
end;
$$ language plpgsql security definer;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user_roles();

