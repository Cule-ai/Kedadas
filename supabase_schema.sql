-- Añadir columna 'grupo' a las tablas existentes para filtrar por grupo
alter table public."Turnos" add column if not exists grupo text default 'Amigos';
alter table public.votaciones add column if not exists grupo text default 'Amigos';
alter table public.mensajes add column if not exists grupo text default 'Amigos';
alter table public.perfiles add column if not exists grupos text default '["Amigos"]';

-- =========================================================================
-- ACTIVACIÓN DE ROW LEVEL SECURITY (RLS)
-- =========================================================================
alter table public.perfiles enable row level security;
alter table public."Turnos" enable row level security;
alter table public.votaciones enable row level security;
alter table public.mensajes enable row level security;
alter table public.suscripciones_push enable row level security;
alter table public.passkeys enable row level security;

-- POLÍTICAS: PERFILES
create policy "Lectura pública/anónima de perfiles"
  on public.perfiles for select using (true);

create policy "Usuarios autenticados editan su propio perfil"
  on public.perfiles for update using (
    auth.uid() = user_id or auth.role() = 'service_role'
  );

-- POLÍTICAS: TURNOS
create policy "Lectura abierta de cuadrantes"
  on public."Turnos" for select using (true);

create policy "Creación e inserción de turnos propios"
  on public."Turnos" for insert with check (
    -- Permite guardar si coincide el usuario o si aún se usa el cliente público
    auth.uid() is null or auth.uid() = usuario_id or usuario is not null
  );

create policy "Modificación de turnos"
  on public."Turnos" for update using (
    auth.uid() is null or auth.uid() = usuario_id or usuario is not null
  );

-- POLÍTICAS: MENSAJES (Chat)
create policy "Lectura de mensajes para todos"
  on public.mensajes for select using (true);

create policy "Inserción de mensajes"
  on public.mensajes for insert with check (true);

create policy "Borrado de mensajes propios o admin"
  on public.mensajes for delete using (true);

-- POLÍTICAS: VOTACIONES
create policy "Lectura de votaciones"
  on public.votaciones for select using (true);

create policy "Votar en opciones"
  on public.votaciones for update using (true);

-- POLÍTICAS: SUSCRIPCIONES PUSH
create policy "Gestión de suscripciones push"
  on public.suscripciones_push for all using (true);

-- POLÍTICAS: PASSKEYS
create policy "Lectura y registro de passkeys"
  on public.passkeys for all using (true);

-- =========================================================================
-- TRIGGER AUTOMÁTICO AL REGISTRAR UN NUEVO USUARIO EN SUPABASE AUTH
-- =========================================================================
create or replace function public.handle_new_user()
returns trigger as $$
begin
  insert into public.perfiles (user_id, email, nombre, rol)
  values (
    new.id,
    new.email,
    coalesce(new.raw_user_meta_data->>'nombre', split_part(new.email, '@', 1)),
    coalesce(new.raw_user_meta_data->>'rol', 'usuario')
  )
  on conflict (nombre) do update set
    user_id = excluded.user_id,
    email = excluded.email;
  return new;
end;
$$ language plpgsql security definer;

-- Asociar el trigger a auth.users
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();
