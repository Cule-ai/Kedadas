-- 1. Habilitar extensión para UUIDs si no está habilitada
create extension if not exists "uuid-ossp";

-- 2. TABLA DE PERFILES (Vinculada opcionalmente a Supabase Auth)
create table if not exists public.perfiles (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references auth.users(id) on delete cascade,
  nombre text not null unique,
  email text,
  pin text, -- Mantenido para retrocompatibilidad con PIN
  rol text not null default 'usuario', -- 'admin' o 'usuario'
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 3. TABLA DE TURNOS (Cuadrante)
create table if not exists public."Turnos" (
  id bigint generated by default as identity primary key,
  dia integer not null,
  usuario text not null,
  usuario_id uuid references auth.users(id) on delete set null,
  indiceEstado integer not null default 0,
  mes_anio text not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  constraint unique_usuario_dia_mes unique (usuario, dia, mes_anio)
);

-- 4. TABLA DE VOTACIONES
create table if not exists public.votaciones (
  id bigint generated by default as identity primary key,
  opcion text not null,
  votantes text default '[]', -- JSON string con nombres de votantes
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 5. TABLA DE MENSAJES (Tablón / Chat)
create table if not exists public.mensajes (
  id bigint generated by default as identity primary key,
  usuario text not null,
  usuario_id uuid references auth.users(id) on delete set null,
  texto text not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 6. TABLA DE SUSCRIPCIONES PUSH (Web Push para iOS/Android)
create table if not exists public.suscripciones_push (
  id uuid primary key default gen_random_uuid(),
  usuario text not null,
  endpoint text not null unique,
  p256dh text not null,
  auth text not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 8. TABLA DE GRUPOS (Amigos, Familia, Pareja, Hijos, etc.)
create table if not exists public.grupos (
  id text primary key,
  nombre text not null,
  icono text default '👥',
  descripcion text,
  creador text,
  miembros text default '[]', -- JSON array con nombres de miembros
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

